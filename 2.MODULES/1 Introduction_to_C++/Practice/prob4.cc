// #include <iostream>
// Provides input and output functionality, allowing the use of cout and cin.

#include <iostream>

// Allows the use of standard library objects like cout and cin
// without writing std:: before them.
using namespace std;

// Program execution starts from the main() function.
int main()
{
    // Prints text to the console.
    cout << "Hello, World!" << endl;

    // Indicates that the program executed successfully.
    return 0;
}

#include <iostream> // This line includes the iostream library, which allows us to use input and output streams, such as cout for printing to the console.
using namespace std; // This line allows us to use names from the standard namespace (std) without having to prefix them with std::, making the code cleaner and easier to read.
int main() {
    cout << "Hello, World!" << endl;
    return 0;
}
// The main function is the entry point of the program. It is where the execution of the program begins.
// The cout object is used to output data to the console. In this case, it prints "Hello, World!" followed by a newline character (endl).
// The return 0; statement indicates that the program has executed successfully and is returning control to the operating system. A return value of 0 typically signifies that the program completed without errors.



















